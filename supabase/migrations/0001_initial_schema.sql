create extension if not exists pgcrypto;

do $$ begin
  create type public.app_role as enum (
    'guru', 'sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.request_status as enum ('diproses', 'revisi', 'disetujui');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.stage_state as enum ('done', 'active', 'pending', 'revisi');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role public.app_role not null default 'guru',
  title text not null default '',
  unit text not null default '',
  avatar text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.budget_lines (
  id text primary key,
  name text not null,
  code text not null default '',
  unit text not null default '',
  annual_limit numeric(15,2) not null default 0,
  used_amount numeric(15,2) not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.fund_requests (
  id text primary key,
  code text not null unique,
  title text not null,
  school_unit text not null,
  budget_category_id text not null,
  budget_category_name text not null,
  unit text not null default '',
  requester_id uuid not null references public.profiles(id),
  requester_name text not null,
  requester_role text not null,
  submitted_date text not null,
  target_date text not null,
  attachment_name text not null default '',
  status public.request_status not null default 'diproses',
  current_stage_step integer not null default 1 check (current_stage_step between 1 and 6),
  revision_note text,
  revision_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.request_items (
  id text primary key,
  request_id text not null references public.fund_requests(id) on delete cascade,
  name text not null,
  quantity numeric(15,3) not null default 0,
  unit_label text not null default '',
  unit_price numeric(15,2) not null default 0
);

create table if not exists public.approval_stages (
  id bigint generated by default as identity primary key,
  request_id text not null references public.fund_requests(id) on delete cascade,
  step integer not null check (step between 1 and 6),
  role_key public.app_role not null,
  role_label text not null,
  person_name text not null,
  person_title text not null default '',
  state public.stage_state not null default 'pending',
  note text,
  timestamp_label text,
  unique (request_id, step)
);

create index if not exists fund_requests_requester_idx on public.fund_requests(requester_id);
create index if not exists fund_requests_status_idx on public.fund_requests(status);
create index if not exists request_items_request_idx on public.request_items(request_id);
create index if not exists approval_stages_request_idx on public.approval_stages(request_id);

-- Role lookup used by RLS. A user cannot assign themselves a higher role.
create or replace function public.current_app_role()
returns public.app_role
language sql stable security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid()
$$;

alter table public.profiles enable row level security;
alter table public.budget_lines enable row level security;
alter table public.fund_requests enable row level security;
alter table public.request_items enable row level security;
alter table public.approval_stages enable row level security;

-- Profiles: users can read profiles for display; only director can manage roles/profiles.
drop policy if exists "profiles_read_authenticated" on public.profiles;
create policy "profiles_read_authenticated" on public.profiles
for select to authenticated using (true);

drop policy if exists "profiles_director_manage" on public.profiles;
create policy "profiles_director_manage" on public.profiles
for all to authenticated
using (public.current_app_role() = 'direktur')
with check (public.current_app_role() = 'direktur');

-- Budget is visible to signed-in staff; only director and treasurers can change it.
drop policy if exists "budget_read_authenticated" on public.budget_lines;
create policy "budget_read_authenticated" on public.budget_lines
for select to authenticated using (true);

drop policy if exists "budget_manage_authorized" on public.budget_lines;
create policy "budget_manage_authorized" on public.budget_lines
for all to authenticated
using (public.current_app_role() in ('direktur', 'bendahara-sekolah', 'bendahara-umum'))
with check (public.current_app_role() in ('direktur', 'bendahara-sekolah', 'bendahara-umum'));

-- Signed-in staff can view requests. Request owner may create their own request;
-- reviewers/director may update requests during the approval workflow.
drop policy if exists "requests_read_authenticated" on public.fund_requests;
create policy "requests_read_authenticated" on public.fund_requests
for select to authenticated using (true);

drop policy if exists "requests_insert_own" on public.fund_requests;
create policy "requests_insert_own" on public.fund_requests
for insert to authenticated
with check (requester_id = auth.uid());

drop policy if exists "requests_update_owner_or_reviewer" on public.fund_requests;
create policy "requests_update_owner_or_reviewer" on public.fund_requests
for update to authenticated
using (
  requester_id = auth.uid()
  or public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur')
)
with check (
  requester_id = auth.uid()
  or public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur')
);

drop policy if exists "requests_delete_owner_pending" on public.fund_requests;
create policy "requests_delete_owner_pending" on public.fund_requests
for delete to authenticated
using (requester_id = auth.uid() and status <> 'disetujui');

-- Child rows follow access to their parent request.
drop policy if exists "items_read_authenticated" on public.request_items;
create policy "items_read_authenticated" on public.request_items
for select to authenticated using (true);

drop policy if exists "items_manage_request_owner_or_reviewer" on public.request_items;
create policy "items_manage_request_owner_or_reviewer" on public.request_items
for all to authenticated
using (
  exists (
    select 1 from public.fund_requests r
    where r.id = request_id
      and (r.requester_id = auth.uid()
        or public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur'))
  )
)
with check (
  exists (
    select 1 from public.fund_requests r
    where r.id = request_id
      and (r.requester_id = auth.uid()
        or public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur'))
  )
);

drop policy if exists "stages_read_authenticated" on public.approval_stages;
create policy "stages_read_authenticated" on public.approval_stages
for select to authenticated using (true);

drop policy if exists "stages_manage_authorized" on public.approval_stages;
create policy "stages_manage_authorized" on public.approval_stages
for all to authenticated
using (
  public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur')
)
with check (
  public.current_app_role() in ('sarana', 'bendahara-sekolah', 'bendahara-umum', 'direktur')
);

